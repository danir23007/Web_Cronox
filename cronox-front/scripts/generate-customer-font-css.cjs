// Keep the official WOFF2 files intact. Restrict their CSS coverage to letters
// and combining diacritics; every other character uses the context's old font.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'assets/fonts/cormorant-garamond/provenance.json'), 'utf8'));
const alphabetic = /[\p{L}\p{M}]/u;
// Unicode classifies a few typographic signs as letters for compatibility.
// Ordinal indicators, the micro/litre signs and apostrophe/accent modifiers
// still belong to the old typeface under the site's letters-only policy.
const signs = new Set([0x00aa, 0x00b5, 0x00ba, 0x02bb, 0x02bc, 0x02c6, 0x2113]);
const lettersOnly = range => {
  const codes = [];
  for (const part of range.split(',')) {
    const [start, end = start] = part.trim().replace(/^U\+/, '').split('-').map(value => parseInt(value, 16));
    for (let code = start; code <= end; code++) if (!signs.has(code) && alphabetic.test(String.fromCodePoint(code))) codes.push(code);
  }
  const sorted = [...new Set(codes)].sort((a, b) => a - b), ranges = [];
  for (let i = 0; i < sorted.length; i++) {
    const start = sorted[i]; let end = start;
    while (sorted[i + 1] === end + 1) end = sorted[++i];
    const hex = value => value.toString(16).toUpperCase().padStart(4, '0');
    ranges.push(`U+${hex(start)}${end === start ? '' : '-' + hex(end)}`);
  }
  return ranges.join(', ');
};
const header = `/* Official Cormorant Garamond v21; SIL OFL 1.1. See fonts/cormorant-garamond/.
   Generated by scripts/generate-customer-font-css.cjs. Letters and combining
   diacritics only: digits, punctuation, symbols AND whitespace fall through
   to each component's original font. Upright is the only style currently used. */\n`;
const css = manifest.files.map(source => `@font-face {
  font-family: 'Cormorant Garamond';
  font-style: ${source.style};
  font-weight: ${source.weight};
  font-display: swap;
  src: url('./fonts/cormorant-garamond/${source.file}') format('woff2');
  unicode-range: ${lettersOnly(source.unicodeRange)};
}\n`).join('\n');
fs.writeFileSync(path.join(root, 'assets/customer-fonts.css'), header + css);
const central = path.join(root, 'assets/customer-typography.css');
const fallbackRange = lettersOnly(manifest.files.map(source => source.unicodeRange).join(', '));
fs.writeFileSync(central, fs.readFileSync(central, 'utf8').replace(
  /unicode-range: [^\n]+; \/\* generated letters \*\//g,
  `unicode-range: ${fallbackRange}; /* generated letters */`,
));
