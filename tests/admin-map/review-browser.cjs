    await recordGeometry(page,'desktop-error');
    await expect(page.locator('.map-legend')).toContainText('Ventas no disponibles');
    await expect(page.locator('.map-status')).not.toContainText('No hay pedidos');
    await page.locator('.map-graphic [data-region="19"]').focus();
    await expect(page.locator('.map-tooltip')).toContainText('Melilla');
    await expect(page.locator('.map-tooltip')).toContainText('Ventas no disponibles');
    await page.evaluate(()=>window.scrollTo(0,0));
    await page.screenshot({path:path.join(out,'desktop-error.png')});
    await page.screenshot({path:path.join(out,'error.png')});
    await page.unroute('**/api/admin/map?**'); await page.locator('[data-retry]').click();
