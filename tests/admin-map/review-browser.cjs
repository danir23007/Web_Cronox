  const server=start(43128),browser=await chromium.launch({headless:true});
  const out=path.resolve('output/playwright/admin-map'); await fs.mkdir(out,{recursive:true});
  const context=await browser.newContext({viewport:{width:1440,height:1100}});
  const page=await context.newPage(), errors=[], mutations=[], external=[], dialogs=[];
  const resources=[],geometry=[];
  page.on('response',response=> { if(response.url().includes('/assets/maps/spain-communities.svg')) resources.push({url:response.url(),status:response.status(),type:response.headers()['content-type']}); });
