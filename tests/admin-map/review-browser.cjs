    await phone.goto('http://127.0.0.1:43128/admin.html#section-map');
    await expect(phone.locator('.map-graphic svg')).toBeVisible();
    await phone.getByRole('switch',{name:'Modo oscuro'}).tap();
    await phone.locator('#sidebarToggle').tap(); await expect(phone.locator('#adminSidebar')).toBeVisible();
    await expect(phone.locator('nav > .sidebar-destination[data-nav-target="section-map"]')).toBeVisible();
    await expect(phone.locator('nav > .sidebar-destination[data-nav-target="section-map"]')).toBeInViewport();
    await expect.poll(async()=>Math.abs((await phone.locator('#adminSidebar').boundingBox()).x)<1).toBe(true);
    await expect(phone.locator('[aria-controls="navCliente"]')).toHaveAttribute('aria-expanded','false');
    await phone.screenshot({path:path.join(out,'mobile-menu.png')});
    await phone.locator('[data-nav-target="section-map"]').tap();
