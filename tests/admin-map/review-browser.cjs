    await page.locator('[name="preset"]').selectOption('all');
    await expect(page.locator('[name="from"]')).toHaveValue('2000-01-01');
    await expect(page.locator('.map-status')).toBeEmpty();
    await page.evaluate(()=>window.CRONOX_ADMIN_NAV.navigate('section-orders'));
    await expect(page.locator('#section-orders')).toBeVisible();
    await page.goBack();
