    releaseSales();
    await expect(page.locator('.map-graphic [data-region]')).toHaveCount(19);
    await expect(page.locator('.map-regions-table tbody tr')).toHaveCount(19);
    await expect(page.locator('[name="preset"]')).toHaveValue('month');
    await expect(page.locator('.map-cards').getByText('90',{exact:true})).toBeVisible();
    await page.unroute('**/api/admin/map?**');
    await expect(page.locator('.map-legend')).toContainText('0');
    const madrid=page.locator('.map-graphic [data-region="13"]');
    await madrid.hover(); await expect(page.locator('.map-tooltip')).toContainText('Comunidad de Madrid');
