    await page.keyboard.press('Enter');
    await expect(page.locator('.map-detail')).toBeVisible();
    await expect(page.locator('.map-detail [data-order]')).toHaveCount(25);
    await expect(madrid).toBeFocused();
    await page.locator('.map-detail [data-page="1"]').click();
    await expect(page.locator('.map-pagination')).toContainText('Página 2');
    await expect(page.locator('.map-detail [data-order]')).toHaveCount(12);
    await page.locator('.map-detail [data-order]').first().click();
    await expect(page.locator('#orderDetailModal')).toBeVisible();
    await page.locator('#orderDetailClose').click();
    await page.locator('[name="metric"]').selectOption('revenueCents');
    await expect(page.locator('.map-legend')).toContainText('€');
    await page.locator('[data-sort="name"]').click();
    await expect(page.locator('[data-column="name"]')).toHaveAttribute('aria-sort','descending');
    await page.getByRole('switch',{name:'Modo oscuro'}).click();
