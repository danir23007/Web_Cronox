    await phone.goto('http://127.0.0.1:43128/admin.html#section-map?from=2000-01-01&to=2000-01-02&preset=custom');
    await expect(phone.locator('.map-status')).toHaveText('No hay pedidos pagados en este período');
    await recordGeometry(phone,'mobile-empty');
    expect(await phone.locator('.map-graphic [data-region]').evaluateAll(nodes=>nodes.every(n=>n.style.fill==='rgb(68, 68, 77)'))).toBe(true);
    await phone.locator('.map-graphic [data-region="19"]').tap();
    await expect(phone.locator('.map-tooltip')).toContainText('Melilla');
    await expect(phone.locator('.map-detail')).toContainText('No hay pedidos pagados');
    await phone.locator('.map-cartography').screenshot({path:path.join(out,'mobile-empty.png')});
    await phone.route('**/api/admin/map?**',route=>route.fulfill({status:500,body:'simulated failure'}));
    await phone.locator('[name="preset"]').selectOption('month');
    await expect(phone.locator('[data-retry]')).toBeVisible();
    await recordGeometry(phone,'mobile-error');
    await phone.locator('.map-graphic [data-region="18"]').tap();
    await expect(phone.locator('.map-tooltip')).toContainText('Ceuta');
    await expect(phone.locator('.map-tooltip')).toContainText('Ventas no disponibles');
