// Normal persistent localhost, using a synthetic local product. Log in normally first.
async (page) => {
  const check = (value, message) => { if (!value) throw new Error(message); };
  const errors = [], responses = [], points = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.url().includes('/api/admin/sale-points') || r.url().includes('/api/admin/finance')) responses.push({ status:r.status(), path:new URL(r.url()).pathname }); });
  if (await page.locator('.pos-editor [data-action=cancel]').count()) await page.locator('.pos-editor [data-action=cancel]').click();
  await page.reload(); // Load the updated document/assets once before the scenario.
  for (const width of [1440,390]) {
    await page.setViewportSize({width,height:900});
    await page.goto('http://localhost:3000/admin.html#section-sale-points');
    await page.getByRole('heading', {name:'Puntos de venta',exact:true}).waitFor();
    check(await page.evaluate(() => window.CRONOX_API.API_BASE) === 'http://localhost:3000', 'Unexpected API destination');
    const name=`TEST local botones ${width}px ${Date.now()}`;
    await page.getByRole('button', {name:'Crear punto de venta',exact:true}).click();
    await page.getByLabel('Nombre / edición').fill(name);
    await page.locator('.pos-editor select[name=type]').selectOption('EVENT');
    await page.getByLabel('Ciudad',{exact:true}).fill('Local de prueba');
    await page.getByLabel('Comisión predeterminada (%)').fill('20');
    await page.getByRole('button', {name:'Guardar',exact:true}).click();
    await page.getByRole('heading', {name,exact:true}).waitFor();
    const id=new URLSearchParams(new URL(page.url()).hash.split('?')[1]).get('point');
    await page.getByRole('button', {name:'Registrar venta',exact:true}).click();
    const variant=await page.getByLabel('Producto y talla').locator('option').evaluateAll(nodes => nodes.find(n => n.textContent.includes('Prenda TEST local puntos 2026-10-12')).value);
    await page.getByLabel('Producto y talla').selectOption(variant);
    await page.getByLabel('Cantidad',{exact:true}).fill('2');
    await page.getByLabel('Precio pagado por unidad (€)').fill('25.50');
    await page.getByRole('button', {name:'Guardar',exact:true}).click();
    await page.locator('.pos-editor').waitFor({state:'detached'});
    await page.getByRole('button', {name:'Registrar gasto',exact:true}).click();
    await page.getByLabel('Descripción',{exact:true}).fill('Gasto TEST local de participación');
    await page.getByLabel('Importe (€)').fill('5');
    await page.getByRole('button', {name:'Guardar',exact:true}).click();
    await page.locator('.pos-editor').waitFor({state:'detached'});
    const detail=await(await page.request.get(`http://localhost:3000/api/admin/sale-points/${id}?from=2026-10-01&to=2026-10-31`)).json();
    check(detail.report.totals.revenueCents===5100 && detail.report.totals.costCents===3000 && detail.report.totals.commissionCents===1020 && detail.report.totals.fixedExpenseCents===500 && detail.report.totals.profitCents===580,'Point finance');
    const finance=await(await page.request.get(`http://localhost:3000/api/admin/finance?from=2026-10-01&to=2026-10-31&source=points&pointId=${id}`)).json();
    check(finance.totals.profitCents===580 && finance.buckets.reduce((s,b)=>s+b.profitCents,0)===580 && finance.salesCount===1,'General finance reconciliation');
    await page.screenshot({path:`output/playwright/normal-local-points-${width}.png`,fullPage:true});
    await page.getByRole('button', {name:'Editar punto',exact:true}).click();
    check((await page.locator('.pos-archive-explanation').innerText()).includes('Conserva'),'Archive explanation');
    await page.getByLabel('Lugar',{exact:true}).fill('Edición comprobada desde el panel');
    await page.getByLabel('Archivado (conserva todo el historial)').check();
    await page.getByRole('button', {name:'Guardar',exact:true}).click();
    await page.locator('.pos-editor').waitFor({state:'detached'});
    check(await page.getByRole('button',{name:'Registrar venta',exact:true}).isDisabled(),'Archived point');
    check(await page.getByRole('button',{name:'Registrar gasto',exact:true}).isDisabled(),'Archived expense');
    await page.getByText('Punto archivado',{exact:true}).waitFor();
    check((await page.locator('#pos-archived-help').innerText()).includes('No puedes registrar'),'Visible archived explanation');
    const archived=await(await page.request.get(`http://localhost:3000/api/admin/sale-points/${id}?from=2026-10-01&to=2026-10-31`)).json();
    check(archived.report.totals.profitCents===580 && archived.sales.length===1 && archived.entries.some(e=>e.kind==='EXPENSE'),'Archiving preserves history');
    const archivedFinance=await(await page.request.get(`http://localhost:3000/api/admin/finance?from=2026-10-01&to=2026-10-31&source=points&pointId=${id}`)).json();
    check(archivedFinance.totals.profitCents===580,'Archived general contribution retained');
    await page.screenshot({path:`output/playwright/normal-local-points-archived-${width}.png`,fullPage:true});
    const beforeReactivateURL=page.url();
    await page.getByRole('button',{name:'Reactivar',exact:true}).click();
    await page.locator('.pos-archive-status').waitFor({state:'detached'});
    check(page.url()===beforeReactivateURL,'Reactivation without navigation/reload');
    check(await page.getByRole('button',{name:'Registrar venta',exact:true}).isEnabled() && await page.getByRole('button',{name:'Registrar gasto',exact:true}).isEnabled(),'Reactivated buttons');
    await page.getByRole('button',{name:'Registrar venta',exact:true}).click();
    await page.locator('.pos-editor [data-lines]').waitFor();
    await page.locator('.pos-editor [data-action=cancel]').click();
    await page.getByRole('button',{name:'Registrar gasto',exact:true}).click();
    await page.getByLabel('Descripción',{exact:true}).fill('TEST gasto tras reactivar');
    await page.getByLabel('Importe (€)').fill('3');
    await page.getByRole('button',{name:'Guardar',exact:true}).click();
    await page.locator('.pos-editor').waitFor({state:'detached'});
    await page.reload(); await page.getByRole('heading',{name,exact:true}).waitFor();
    check(await page.getByRole('button',{name:'Registrar venta',exact:true}).isEnabled(),'Persistent active state');
    check((await page.locator('.pos-metrics').innerText()).includes('2,80'),'Persistent statistics');
    await page.goto(`http://localhost:3000/admin.html#section-money?from=2026-10-01&to=2026-10-31&source=points&pointId=${id}`);
    await page.locator('[data-finance-page=money] .finance-content[aria-busy=false]').waitFor();
    check((await page.locator('[data-finance-page=money] .profit strong').innerText()).includes('2,80'),'General finance panel KPI');
    points.push({id,width,archivedThenReactivated:true,revenueCents:5100,profitCents:280});
  }
  check(errors.length===0,'JS errors: '+errors.join('; '));
  check(responses.length>0 && responses.every(r=>r.status>=200 && r.status<300),'Endpoint errors');
  await page.goto('http://localhost:3000/admin.html#section-sale-points');
  return {passed:true,url:'http://localhost:3000/admin.html#section-sale-points',points,errors,responses};
}
