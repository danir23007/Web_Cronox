-- Financial history stays append-only. Only zero-value creation/edit metadata
-- can be removed as part of a confirmed, locked, empty-point deletion.
CREATE OR REPLACE FUNCTION cronox_point_entry_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' AND current_setting('cronox.empty_point_delete',true)=OLD."pointId"
    AND OLD.kind IN ('POINT_CREATE','POINT_EDIT') AND OLD."expenseCents"=0 AND OLD.lines='[]'::jsonb THEN RETURN OLD; END IF;
 RAISE EXCEPTION 'PointEntry is append-only; record a correction or reversal';
END $$;
COMMIT;
